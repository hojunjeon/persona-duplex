from __future__ import annotations

import argparse
import csv
import math
import statistics
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path


RUNTIME_ENV = {
    "qwen": ("qwen_ws", "Qwen/Qwen3-ASR-1.7B"),
    "elevenlabs": ("elevenlabs_ws", "scribe_v2_realtime"),
    "soniox": ("soniox_ws", "stt-rt-v5"),
    "deepgram": ("deepgram_ws", "nova-3"),
}


@dataclass(frozen=True)
class Summary:
    provider: str
    count: int
    mean_cer: float
    median_cer: float
    p90_final_ms: float
    p90_first_partial_ms: float
    mean_rtf: float


def percentile(values: list[float], q: float) -> float:
    if not values:
        return math.inf
    values = sorted(values)
    if len(values) == 1:
        return values[0]
    index = (len(values) - 1) * q
    lo = math.floor(index)
    hi = math.ceil(index)
    if lo == hi:
        return values[lo]
    return values[lo] * (hi - index) + values[hi] * (index - lo)


def parse_float(value: str | None) -> float | None:
    try:
        return float(value) if value not in {None, ""} else None
    except (TypeError, ValueError):
        return None


def summarize(path: Path) -> list[Summary]:
    groups: dict[str, list[dict[str, str]]] = defaultdict(list)
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        for row in csv.DictReader(handle):
            provider = (row.get("provider") or "").strip()
            if provider not in RUNTIME_ENV or (row.get("error") or "").strip():
                continue
            if parse_float(row.get("cer")) is None:
                continue
            groups[provider].append(row)

    result: list[Summary] = []
    for provider, rows in groups.items():
        cers = [float(row["cer"]) for row in rows]
        finals = [v for row in rows if (v := parse_float(row.get("final_after_end_ms"))) is not None]
        partials = [v for row in rows if (v := parse_float(row.get("first_partial_ms"))) is not None]
        rtfs = [v for row in rows if (v := parse_float(row.get("rtf"))) is not None]
        result.append(
            Summary(
                provider=provider,
                count=len(rows),
                mean_cer=statistics.fmean(cers),
                median_cer=statistics.median(cers),
                p90_final_ms=percentile(finals, 0.90),
                p90_first_partial_ms=percentile(partials, 0.90),
                mean_rtf=statistics.fmean(rtfs) if rtfs else math.inf,
            )
        )
    return result


def choose(items: list[Summary], policy: str, max_final_ms: float) -> Summary:
    if not items:
        raise RuntimeError("실행 가능한 스트리밍 STT의 성공 결과가 없습니다.")
    eligible = [item for item in items if item.p90_final_ms <= max_final_ms]
    pool = eligible or items
    if policy == "accuracy":
        return min(pool, key=lambda x: (x.mean_cer, x.p90_final_ms, x.p90_first_partial_ms))
    if policy == "latency":
        return min(pool, key=lambda x: (x.p90_final_ms, x.p90_first_partial_ms, x.mean_cer))
    # Balanced: CER dominates, but a full extra second after speech end costs 0.08.
    return min(
        pool,
        key=lambda x: (
            x.mean_cer + 0.08 * min(x.p90_final_ms, 5000) / 1000 + 0.025 * min(x.p90_first_partial_ms, 5000) / 1000,
            x.mean_cer,
        ),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Choose the best real-time STT from benchmark_stt.py output")
    parser.add_argument("results", type=Path)
    parser.add_argument("--policy", choices=("accuracy", "balanced", "latency"), default="balanced")
    parser.add_argument("--max-final-ms", type=float, default=1200.0)
    parser.add_argument("--output", type=Path, default=Path("benchmark/selected_stt.env"))
    args = parser.parse_args()

    summaries = summarize(args.results)
    selected = choose(summaries, args.policy, args.max_final_ms)
    mode, model = RUNTIME_ENV[selected.provider]
    lines = [
        "# Generated by benchmark/select_best.py",
        f"# policy={args.policy} count={selected.count} mean_cer={selected.mean_cer:.5f} p90_final_ms={selected.p90_final_ms:.1f}",
        f"STT_MODE={mode}",
        f"STT_CLOUD_MODEL={model}",
    ]
    if selected.provider == "qwen":
        lines.append(f"ASR_MODEL_ID={model}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print("provider,count,mean_cer,p90_final_ms,p90_first_partial_ms,mean_rtf")
    for item in sorted(summaries, key=lambda x: x.mean_cer):
        print(
            f"{item.provider},{item.count},{item.mean_cer:.5f},{item.p90_final_ms:.1f},"
            f"{item.p90_first_partial_ms:.1f},{item.mean_rtf:.4f}"
        )
    print(f"selected={selected.provider} output={args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
